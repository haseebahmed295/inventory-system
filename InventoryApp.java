/**
 * Application entry point alias for the Inventory Management System.
 * Inherits full JavaFX UI functionality from Main.
 *
 * @author Haseeb Ahmad
 * @version 1.0
 */
public class InventoryApp extends Main {

    /** Default constructor. */
    public InventoryApp() {
        super();
    }

    /**
     * Application launcher.
     *
     * @param args command-line arguments
     */
    public static void main(String[] args) {
        launch(args);
    }
}
